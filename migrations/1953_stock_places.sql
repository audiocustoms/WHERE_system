-- In-house movements of stock: issue to a place of the house, take it back, move it.
--
-- A **place** (`where_place`) is where material stands while it is in use — `Foyer`,
-- `Podium`, `Bühne`. It is not a warehouse: the piece is still ours, but it is no longer
-- in the shelf, and that is what `"Bestand_Entnahme*"` counts. Places are master data and
-- stay even when a device leaves them.
--
-- The device row keeps its warehouse while it is issued — so the stock of the warehouse
-- remains the own stock (like the legacy columns assume) and `Verfügbar` = total − issued.
--
-- No foreign keys on purpose (as in `where_stock_movement`): a deleted place must not take
-- the booking with it; the history keeps what happened.

CREATE TABLE IF NOT EXISTS "where_place" (
    "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "name" text NOT NULL,
    "note" text,
    "active" boolean NOT NULL DEFAULT true,
    "created_at" timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "where_place_name_idx"
    ON "where_place" (lower("name"));

COMMENT ON TABLE "where_place" IS
    'Place of the house where material stands while it is in use (Foyer, Podium, …)';

ALTER TABLE "Seriennummern" ADD COLUMN IF NOT EXISTS "where_place_id" integer;
ALTER TABLE "Seriennummern" ADD COLUMN IF NOT EXISTS "where_issued_from" date;
ALTER TABLE "Seriennummern" ADD COLUMN IF NOT EXISTS "where_issued_until" date;

CREATE INDEX IF NOT EXISTS "Seriennummern_where_place_idx"
    ON "Seriennummern" ("where_place_id")
    WHERE "where_place_id" IS NOT NULL;

COMMENT ON COLUMN "Seriennummern"."where_place_id" IS
    'Place the device stands at while it is issued (NULL = in the warehouse)';
COMMENT ON COLUMN "Seriennummern"."where_issued_from" IS
    'Day the device was handed out';
COMMENT ON COLUMN "Seriennummern"."where_issued_until" IS
    'Day the device is expected back (NULL = no date agreed)';

-- The history keeps the place as well: an issue reads "Hauptlager → Foyer".
ALTER TABLE "where_stock_movement" ADD COLUMN IF NOT EXISTS "place_from" integer;
ALTER TABLE "where_stock_movement" ADD COLUMN IF NOT EXISTS "place_to" integer;

COMMENT ON COLUMN "where_stock_movement"."place_to" IS
    'Place the material went to (NULL = not a movement to a place)';
COMMENT ON COLUMN "where_stock_movement"."place_from" IS
    'Place the material came from (NULL = not a movement from a place)';

-- The three rooms every house has; more are added in the mask itself.
INSERT INTO "where_place" ("name")
VALUES ('Foyer'), ('Podium'), ('Bühne')
ON CONFLICT DO NOTHING;
