-- Stock movements: one row per booking of a device or batch.
--
-- The stock itself stays derived from `"Seriennummern"`; this table is the trace:
-- who booked what, when, and where the piece stood before and after. Serial number,
-- warehouse ids, bin and condition are copied into the row, so the entry keeps its
-- meaning after the device was deleted and after a warehouse was renamed.
--
-- `kind` is one of
--   receipt   — goods receipt (new device or batch)
--   change    — device data changed
--   move      — device moved to another warehouse
--   retire    — device discarded (`"Ausgesondert"` set)
--   reinstate — discard taken back
--   delete    — device removed for good
--
-- No foreign keys on purpose: a deleted device or warehouse must not take the history
-- with it.

CREATE TABLE IF NOT EXISTS "where_stock_movement" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "article_id" integer NOT NULL,
    "device_id" integer NOT NULL,
    "serial_no" text,
    "kind" text NOT NULL,
    "quantity" numeric(18,4),
    "warehouse_from" integer,
    "warehouse_to" integer,
    "bin_from" text,
    "bin_to" text,
    "condition_from" text,
    "condition_to" text,
    "discarded_from" boolean,
    "discarded_to" boolean,
    "note" text,
    "created_at" timestamptz NOT NULL DEFAULT now(),
    "created_by" text NOT NULL,
    PRIMARY KEY ("id")
);

CREATE INDEX IF NOT EXISTS "where_stock_movement_article_idx"
    ON "where_stock_movement" ("article_id", "created_at" DESC);

CREATE INDEX IF NOT EXISTS "where_stock_movement_device_idx"
    ON "where_stock_movement" ("device_id", "created_at" DESC);
