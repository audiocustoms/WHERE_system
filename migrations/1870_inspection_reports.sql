-- Prüfprotokolle (inspection reports) per device, and the article image.
--
-- A Prüfprotokoll belongs to **one device**, not to the article: the paper is bound
-- to the serial and inventory number of that piece. Both numbers are copied into the
-- row when the PDF is uploaded, so the protocol still names the device after a
-- number was corrected later.
--
-- The bytes live in the same content-addressed store as the article files
-- (`<root>/<sha256[0..2]>/<sha256>`); the row here only carries the metadata.

CREATE TABLE IF NOT EXISTS "where_inspection_report" (
    "id"           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- `"Seriennummern"."Primary_Key"`; no foreign key — a device is deleted with the
    -- article and the report then loses its anchor as well.
    "device_id"    integer NOT NULL,
    "article_id"   integer NOT NULL REFERENCES "Artikel" ("Primary_Key") ON DELETE CASCADE,
    "serial_no"    text,
    "inventory_no" text,
    "title"        text NOT NULL,
    "mime"         text,
    "size"         bigint,
    "sha256"       char(64) NOT NULL,
    "uploaded_by"  text,
    "uploaded_at"  timestamptz NOT NULL DEFAULT now(),
    "deleted"      boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS "where_inspection_report_device_idx"
    ON "where_inspection_report" ("device_id") WHERE NOT "deleted";
CREATE INDEX IF NOT EXISTS "where_inspection_report_article_idx"
    ON "where_inspection_report" ("article_id") WHERE NOT "deleted";

-- Article image. The image bytes are a normal entry of `"article_file"` in the
-- folder `bild`; this table only remembers whether the animated placeholder stands
-- in for a missing photo, so the choice survives a reload.
CREATE TABLE IF NOT EXISTS "where_article_image" (
    "article_id"  integer PRIMARY KEY REFERENCES "Artikel" ("Primary_Key") ON DELETE CASCADE,
    "placeholder" boolean NOT NULL DEFAULT false,
    "updated_at"  timestamptz NOT NULL DEFAULT now()
);
