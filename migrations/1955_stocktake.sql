-- Stocktaking (`Inventur`): counting a warehouse against the book.
--
-- A stocktake belongs to **one warehouse**. Starting it copies every device and batch of
-- that warehouse into its lines together with the amount the book says (`book_quantity`).
-- Counting writes `counted_quantity`; finishing the stocktake books the difference as a
-- correction into `"where_stock_movement"` (kind `count`) and recomputes `"Artikel_Env"`,
-- so availability follows.
--
-- The legacy tables `"Inventur"` / `"Artikel_Inventur"` stay untouched for the same reason
-- as `"Artikel_Stock_Historie"`: their columns cannot be proven without the 4D source, and
-- WHERE writes its own journal. Importing the legacy counting documents later only needs a
-- reader, not a writer that guesses.

CREATE TABLE IF NOT EXISTS "where_stocktake" (
    "id"           integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "warehouse_id" integer NOT NULL,
    "name"         text NOT NULL,
    "note"         text,
    -- `open` = being counted, `closed` = differences booked, `cancelled` = dropped
    "state"        text NOT NULL DEFAULT 'open',
    "started_at"   timestamptz NOT NULL DEFAULT now(),
    "started_by"   text NOT NULL,
    "finished_at"  timestamptz,
    "finished_by"  text,
    CONSTRAINT "where_stocktake_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "where_stocktake_state_known"
        CHECK ("state" IN ('open', 'closed', 'cancelled'))
);

CREATE INDEX IF NOT EXISTS "where_stocktake_warehouse_idx"
    ON "where_stocktake" ("warehouse_id", "started_at" DESC);

CREATE TABLE IF NOT EXISTS "where_stocktake_line" (
    "id"               integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "stocktake_id"     integer NOT NULL
                       REFERENCES "where_stocktake" ("id") ON DELETE CASCADE,
    -- `"Seriennummern"."Primary_Key"`; no foreign key, like the journal — the line keeps
    -- its serial number and the article it belonged to even if the device is removed.
    "device_id"        integer NOT NULL,
    "article_id"       integer NOT NULL,
    "article_no"       integer,
    "article_name"     text,
    "serial_no"        text,
    "bin_location"     text,
    -- what the book said when the stocktake was started
    "book_quantity"    numeric NOT NULL,
    -- what was counted; NULL = not counted yet
    "counted_quantity" numeric,
    "counted_at"       timestamptz,
    "counted_by"       text,
    "note"             text,
    CONSTRAINT "where_stocktake_line_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "where_stocktake_line_device" UNIQUE ("stocktake_id", "device_id")
);

CREATE INDEX IF NOT EXISTS "where_stocktake_line_idx"
    ON "where_stocktake_line" ("stocktake_id", "article_no");

COMMENT ON TABLE "where_stocktake" IS
    'Counting of one warehouse against the book; finishing books the differences';
COMMENT ON COLUMN "where_stocktake_line"."book_quantity" IS
    'Amount of the device/batch when the stocktake was started';
COMMENT ON COLUMN "where_stocktake_line"."counted_quantity" IS
    'Amount that was counted; NULL while not counted';
