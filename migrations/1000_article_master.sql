-- Article master: additions for the form in img/articles_01..05.PNG
--
-- Almost every field of the form already exists in "Artikel" and in
-- "Artikel_Beschreibung" (the legacy structure is surprisingly complete here).
-- This migration only adds the three missing columns, the language and article group
-- master data and the file storage on the article.

-- ---------------------------------------------------------------- missing columns
ALTER TABLE "Artikel" ADD COLUMN IF NOT EXISTS "Matchcode" text;
ALTER TABLE "Artikel" ADD COLUMN IF NOT EXISTS "Textsync_Flag" boolean DEFAULT false;
ALTER TABLE "Artikel" ADD COLUMN IF NOT EXISTS "TeamAgenda_Gruppe" varchar(80);

-- Audit as timestamps. The legacy schema keeps date and time separate (ge_createDate + ge_createTime);
-- those columns stay untouched for the later import.
ALTER TABLE "Artikel" ADD COLUMN IF NOT EXISTS "audit_created_at" timestamptz;
ALTER TABLE "Artikel" ADD COLUMN IF NOT EXISTS "audit_changed_at" timestamptz;

-- The article number is the natural key of the form ("Article no. 1001 /").
CREATE UNIQUE INDEX IF NOT EXISTS "Artikel_ArtikelNr_uq" ON "Artikel" ("ArtikelNr");
CREATE INDEX IF NOT EXISTS "Artikel_Matchcode_idx" ON "Artikel" ("Matchcode");
CREATE INDEX IF NOT EXISTS "Artikel_Aktiv_idx" ON "Artikel" ("Aktiv");

-- ---------------------------------------------------------------- Languages
-- "German" as native language so the text blocks of the form have a target.
INSERT INTO "Storage_Sprachen" ("Primary_Key", "Sprache", "Muttersprache", "ISO_639_1", "ISO_639_2")
SELECT 1, 'Deutsch', true, 'de', 'deu'
WHERE NOT EXISTS (SELECT 1 FROM "Storage_Sprachen" WHERE "ISO_639_1" = 'de');

-- ---------------------------------------------------------------- Article groups
-- "Storage_Warengruppe" is modelled as a tree (Index, Parent_ID, Child_ID).
-- The form shows it as a list with +/-; we treat it as nodes with a label.
CREATE INDEX IF NOT EXISTS "Storage_Warengruppe_Index_idx" ON "Storage_Warengruppe" ("Index");
CREATE INDEX IF NOT EXISTS "Artikel_Warengruppe_Artikel_idx" ON "Artikel_Warengruppe" ("Artikel_Primkey");
CREATE INDEX IF NOT EXISTS "Artikel_Warengruppe_Storage_idx" ON "Artikel_Warengruppe" ("Storage_Primkey");

