-- Explicit keys do not consume sequence values: advance the sequence, otherwise the
-- next regular INSERT collides.
SELECT setval(
    pg_get_serial_sequence('"Storage_Warengruppe"', 'Primary_Key'),
    (SELECT GREATEST(COALESCE(MAX("Primary_Key"), 1), 1) FROM "Storage_Warengruppe")
);
SELECT setval(
    pg_get_serial_sequence('"Storage_Sprachen"', 'Primary_Key'),
    (SELECT GREATEST(COALESCE(MAX("Primary_Key"), 1), 1) FROM "Storage_Sprachen")
);

-- ---------------------------------------------------------------- File storage
-- Matches the "file storage" dialog (img/ablage_01.PNG): files and links,
-- optionally in folders, with a version chain and history.
CREATE TABLE IF NOT EXISTS "article_file" (
    "id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "article_id"     integer NOT NULL REFERENCES "Artikel" ("Primary_Key") ON DELETE CASCADE,
    "folder"         text NOT NULL DEFAULT '',
    "name"           text NOT NULL,
    "is_link"       boolean NOT NULL DEFAULT false,
    "link_target"      text,
    "mime"           text,
    "size"        bigint,
    "sha256"         char(64),
    "version"        integer NOT NULL DEFAULT 1,
    "is_current"    boolean NOT NULL DEFAULT true,
    "deleted"      boolean NOT NULL DEFAULT false,
    "uploaded_by" text,
    "uploaded_at" timestamptz NOT NULL DEFAULT now()
);

-- Exactly one file/link per (article, folder, name) is current.
CREATE UNIQUE INDEX IF NOT EXISTS "artikel_datei_aktuell_uq"
    ON "article_file" ("article_id", "folder", "name", "version");
CREATE INDEX IF NOT EXISTS "artikel_datei_artikel_idx"
    ON "article_file" ("article_id") WHERE NOT "deleted";
CREATE INDEX IF NOT EXISTS "artikel_datei_sha256_idx" ON "article_file" ("sha256");

CREATE TABLE IF NOT EXISTS "article_file_history" (
    "id"        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "file_id"  integer NOT NULL REFERENCES "article_file" ("id") ON DELETE CASCADE,
    "aktion"    text NOT NULL,
    "detail"    text,
    "benutzer"  text,
    "zeitpunkt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "artikel_datei_historie_datei_idx" ON "article_file_history" ("file_id");
