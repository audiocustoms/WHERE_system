-- Saved article searches (the "process" selector of the search form).
--
-- The legacy search form has a "process: <name>" row with a dropdown on top; the
-- criteria themselves are process variables (`vt_SearchCondition`) and are gone after
-- closing the form. The legacy application stores such searches in the request table
-- of the respective form.
--
-- WHERE adds its own table for this: a name and the criteria as JSON.
-- The JSON is exactly the body of `POST /api/v1/articles/search` so a
-- saved search can be sent again without conversion.

CREATE TABLE IF NOT EXISTS "where_article_search" (
    "id"           integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    "name"         varchar(120) NOT NULL,
    "criteria"    jsonb NOT NULL,
    "created_at"  timestamptz NOT NULL DEFAULT now(),
    "changed_at" timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY ("id"),
    CONSTRAINT "where_article_search_name_ck" CHECK (btrim("name") <> '')
);

-- A name must be unique (ignoring case).
CREATE UNIQUE INDEX IF NOT EXISTS "where_article_search_name_uq"
    ON "where_article_search" (lower(btrim("name")));
