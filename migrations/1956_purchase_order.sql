-- Purchase orders (`Bestellungen`) of the warehouse: what was ordered for the shelf and
-- how much of it has arrived.
--
-- A purchase order is a warehouse document, not an order of the rental module: it names a
-- supplier, a date and lines of articles with a quantity. Nothing is reserved and nothing
-- is booked until the material arrives — the goods receipt of the article names the line,
-- and the received amount is the sum of the devices that carry that line.
--
-- That is why the received amount is **derived** (`SUM("Menge")` over `"Seriennummern"`
-- with `where_order_line`) and not stored: it cannot drift away from the stock, a
-- correction of the stock corrects the order as well, and a partial delivery is simply a
-- smaller sum. No counter is kept twice.

CREATE TABLE IF NOT EXISTS "where_purchase_order" (
    "id"            integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- Number of the series `purchase_order` (`where_number_series`)
    "number"        text NOT NULL,
    "supplier_no"   integer,
    -- Snapshot of the name: the order keeps its supplier after the address was renamed
    "supplier_name" text,
    "ordered_at"    date NOT NULL DEFAULT CURRENT_DATE,
    "expected_at"   date,
    "note"          text,
    -- `open` = still being delivered, `done` = everything arrived, `cancelled` = dropped
    "state"         text NOT NULL DEFAULT 'open',
    "created_at"    timestamptz NOT NULL DEFAULT now(),
    "created_by"    text NOT NULL DEFAULT '',
    "changed_at"    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT "where_purchase_order_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "where_purchase_order_number" UNIQUE ("number"),
    CONSTRAINT "where_purchase_order_state_known"
        CHECK ("state" IN ('open', 'done', 'cancelled'))
);

CREATE INDEX IF NOT EXISTS "where_purchase_order_state_idx"
    ON "where_purchase_order" ("state", "ordered_at" DESC);

CREATE TABLE IF NOT EXISTS "where_purchase_order_line" (
    "id"           integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "order_id"     integer NOT NULL
                   REFERENCES "where_purchase_order" ("id") ON DELETE CASCADE,
    "line_no"      integer NOT NULL,
    "article_id"   integer NOT NULL,
    -- Snapshots, like the journal: the line stays readable after the article was renamed
    "article_no"   integer,
    "article_name" text,
    "quantity"     numeric NOT NULL,
    "unit_price"   numeric,
    "note"         text,
    CONSTRAINT "where_purchase_order_line_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "where_purchase_order_line_no" UNIQUE ("order_id", "line_no"),
    CONSTRAINT "where_purchase_order_line_positive" CHECK ("quantity" > 0)
);

CREATE INDEX IF NOT EXISTS "where_purchase_order_line_idx"
    ON "where_purchase_order_line" ("order_id", "line_no");
CREATE INDEX IF NOT EXISTS "where_purchase_order_line_article_idx"
    ON "where_purchase_order_line" ("article_id");

-- The goods receipt names the line it belongs to; the received amount is the sum of these
-- devices. No foreign key, like the journal: deleting a line must not delete stock.
ALTER TABLE "Seriennummern"
    ADD COLUMN IF NOT EXISTS "where_order_line" integer;

CREATE INDEX IF NOT EXISTS "Seriennummern_where_order_line_idx"
    ON "Seriennummern" ("where_order_line");

COMMENT ON TABLE "where_purchase_order" IS
    'Purchase order of the warehouse; the received amount of a line is derived from the stock';
COMMENT ON COLUMN "Seriennummern"."where_order_line" IS
    'Line of the purchase order this device arrived on; NULL for a receipt without order';
